import  mongoose from "mongoose";

const userSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
    unique: true,
    lowercase: true,
  },
  password: {
    type: String,
    required: true,
    minlength: 6
  }
}, { timestamps: true });

const websiteUser = mongoose.model("websiteUser",userSchema)

export default websiteUser